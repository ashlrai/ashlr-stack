import { afterEach, beforeEach, describe, expect, it, setDefaultTimeout } from "bun:test";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { type Harness, setupFakePhantom } from "../__tests__/_harness.ts";
import { verificationHintFor, webhookStubFor, wirePhantomForRecipe } from "./phantom-wire.ts";
import type { Recipe } from "./recipe.ts";

// The wiring check spawns the fake `phantom` shim (bash + python3); keep the
// sibling files' raised timeout.
setDefaultTimeout(30_000);

describe("ai/phantom-wire known placeholder nested inside replacement text", () => {
  let harness: Harness;
  let dir: string;

  beforeEach(() => {
    harness = setupFakePhantom();
    dir = mkdtempSync(join(tmpdir(), "wire-nested-placeholder-"));
  });
  afterEach(() => {
    harness.cleanup();
    rmSync(dir, { recursive: true, force: true });
  });

  const recipe = (...names: string[]): Recipe => ({
    id: "nested-placeholder",
    query: "q",
    createdAt: "2026-04-18T00:00:00.000Z",
    providers: names.map((name) => ({ name })),
  });

  it.each([
    "${provider}", // the name slot's own spelling
    "${capitalize(provider)}", // the handler-name slot's spelling
    "${webhookSecretKeyFor(provider)}", // the secret-key slot's spelling
    "${signatureHeaderFor(provider)}", // the header slot's spelling
    "${verificationHintFor(provider)}", // the hint slot's spelling
  ])("never expands the inserted text a second time for the nested token %j", (slot) => {
    // The name is ordinary text carrying one of the template's own slot
    // spellings. This is the decisive re-expansion case: unlike an unknown
    // `${...}` token, this one *would* resolve if the renderer ever fed
    // inserted text back through the slots — a second pass would splice
    // the whole name in again and double the flanking `pre`/`post` text
    // (or recurse forever). The template literal evaluates each slot
    // exactly once, so the carried token must arrive at every expansion
    // site byte-for-byte, still seated between the name's own text.
    const name = `pre${slot}post`;
    const stub = webhookStubFor(name);

    // Case-preserving sites emit the name — token plus surrounding text —
    // byte-for-byte; `capitalize` folds only the first letter at the
    // handler site.
    expect(stub).toContain(`webhook handler stub for ${name}.`);
    expect(stub).toContain(`forge a ${name} webhook.`);
    expect(stub).toContain(`handlePre${slot}postWebhook(req: Request)`);
    // `webhookSecretKeyFor(provider)` uppercases the whole name — token
    // included — at both reveal lines.
    expect(
      stub.split(`phantom reveal PRE${slot.toUpperCase()}POST_WEBHOOK_SECRET`).length - 1,
    ).toBe(2);

    // Five `${...}` spans — one per expansion site — every one the carried
    // token in that site's case, none resolved away or duplicated.
    const tokens = [...stub.matchAll(/\$\{[^}]*\}/g)].map((m) => m[0]);
    expect(tokens).toHaveLength(5);
    for (const token of tokens) expect(token.toLowerCase()).toBe(slot.toLowerCase());

    // The no-second-pass proof: each token still sits between exactly one
    // `pre` and one `post` (in whatever case that site's transform gives
    // them), and the flanking text is never doubled. A re-resolve would
    // have produced `prepre${...}postpost` at every site.
    expect(stub.match(/pre\$\{[^}]*\}post/gi)).toHaveLength(5);
    expect(stub).not.toMatch(/prepre|postpost/i);

    // The remaining slots took their own generic values in the same
    // single pass — the carried token never reached their switch cases.
    expect(stub).toContain('req.headers.get("x-webhook-signature")');
    expect(stub).toContain("//   // Verify per the provider's documented signature scheme.");
    expect(verificationHintFor(name)).toBe(verificationHintFor("zzq"));
  });

  it("emits the nested `${provider}` token literally at all five sites — line-for-line", () => {
    // The sharpest form: the carried token spells the name slot itself, so
    // at the name sites the emitted text is indistinguishable from an
    // unresolved slot. Exact-line equality pins every site: the inserted
    // text arrived verbatim, once, with no re-expansion splicing extra
    // copies of the name around it.
    const stub = webhookStubFor("pre${provider}post");

    expect(stub).toContain(
      "// Auto-generated by `stack apply` — webhook handler stub for pre${provider}post.",
    );
    expect(stub).toContain("//   phantom reveal PRE${PROVIDER}POST_WEBHOOK_SECRET");
    expect(stub).toContain(
      "// export async function handlePre${provider}postWebhook(req: Request): Promise<Response> {",
    );
    expect(stub).toContain("//   // to this endpoint can forge a pre${provider}post webhook.");
    expect(stub).toContain(
      "//   // (`phantom reveal PRE${PROVIDER}POST_WEBHOOK_SECRET`) and compare in",
    );

    // Census: exactly five `${...}` spans — three in original case at the
    // case-preserving sites, two uppercased at the reveal sites. A second
    // pass would have re-resolved each `${provider}` into
    // `pre${provider}post`, doubling the flanks; none appear.
    const tokens = [...stub.matchAll(/\$\{[^}]*\}/g)].map((m) => m[0]);
    expect(tokens).toEqual([
      "${provider}",
      "${PROVIDER}",
      "${provider}",
      "${provider}",
      "${PROVIDER}",
    ]);
    expect(stub).not.toMatch(/prepre|postpost/i);
  });

  it("skips a nested-placeholder name byte-for-byte through wiring and writes nothing for it", async () => {
    // Through `wirePhantomForRecipe` the nested-token name matches no
    // catalog provider: it returns in `skipped` byte-for-byte — token and
    // surrounding text intact — gets no stub on disk, and provokes no vault
    // write. The known provider listed beside it wires normally, unaffected
    // by the placeholder-shaped neighbour.
    const name = "pre${provider}post";
    const stubPath = join(dir, ".stack", "webhooks", "clerk.ts");
    const result = await wirePhantomForRecipe(recipe(name, "clerk"), { cwd: dir });

    expect(result).toEqual({
      present: [],
      missing: ["clerk:CLERK_SECRET_KEY"],
      webhooks: [stubPath],
      skipped: [name],
    });
    expect(result.skipped[0]).toBe(name);

    // Only clerk's documented stub lands — nothing for the nested-token
    // name, and the stub on disk is the same render `webhookStubFor`
    // returns.
    expect(readdirSync(join(dir, ".stack", "webhooks"))).toEqual(["clerk.ts"]);
    expect(readFileSync(stubPath, "utf-8")).toBe(webhookStubFor("clerk"));
    expect(existsSync(join(dir, ".stack", "webhooks", `${name}.ts`))).toBe(false);

    // The whole call log is reads (`--version`, `list`); the vault file
    // still parses to an empty object.
    expect(harness.calls().every((c) => c.cmd === "--version" || c.cmd === "list")).toBe(true);
    expect(harness.callsTo("add")).toEqual([]);
    expect(JSON.parse(readFileSync(harness.vaultPath, "utf-8"))).toEqual({});
  });
});
