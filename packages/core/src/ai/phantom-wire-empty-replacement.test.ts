import { afterEach, beforeEach, describe, expect, it, setDefaultTimeout } from "bun:test";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { type Harness, setupFakePhantom } from "../__tests__/_harness.ts";
import { verificationHintFor, webhookStubFor, wirePhantomForRecipe } from "./phantom-wire.ts";
import type { Recipe } from "./recipe.ts";

// The wiring check spawns the fake `phantom` shim (bash + python3); keep the
// sibling files' raised timeout.
setDefaultTimeout(30_000);

const count = (s: string, needle: string) => s.split(needle).length - 1;

// A name whose only byte has no case mapping: `capitalize` folds it to itself
// and `toUpperCase` leaves it, so it lands byte-identically at all five
// name-fed expansion sites — while still exercising the normal codePointAt
// path, since the `s === ""` early return only fires for the truly empty name.
const SENTINEL = "\u0000";

describe("ai/phantom-wire known placeholder replaced with an empty value", () => {
  let harness: Harness;
  let dir: string;

  beforeEach(() => {
    harness = setupFakePhantom();
    dir = mkdtempSync(join(tmpdir(), "wire-empty-replacement-"));
  });
  afterEach(() => {
    harness.cleanup();
    rmSync(dir, { recursive: true, force: true });
  });

  const recipe = (...names: string[]): Recipe => ({
    id: "empty-replacement",
    query: "q",
    createdAt: "2026-04-18T00:00:00.000Z",
    providers: names.map((name) => ({ name })),
  });

  it("replaces the known placeholder with the empty string and leaves all surrounding text byte-for-byte", () => {
    // Whole-stub differential oracle: the sentinelled render marks every
    // expansion site, and deleting each mark must reproduce the empty render
    // exactly — the strongest form of "surrounding text remains", covering
    // every byte of the template, not just the lines the placeholder sits on.
    const sent = webhookStubFor(SENTINEL);

    // The sentinel reached exactly five sites — one per name-fed slot — so
    // the oracle below is not vacuous: every placeholder was exercised.
    expect(count(sent, SENTINEL)).toBe(5);

    // Removing the placeholder's replacement value leaves the empty render:
    // the slot emitted "" and nothing else moved anywhere in the output.
    expect(sent.replaceAll(SENTINEL, "")).toBe(webhookStubFor(""));
  });

  it("emits the empty replacement at all five sites with each surrounding line intact", () => {
    // Full-line equality (not substring presence): each placeholder line is
    // byte-exact — the slot vanished into "" and the rest of the line kept
    // its fixed text with no extra residue appended to it.
    const stub = webhookStubFor("");
    const lines = stub.split("\n");

    // `${provider}` sites: the name vanished between the fixed prose — a
    // trailing period after "for " and a doubled space inside "forge a".
    expect(lines).toContain("// Auto-generated by `stack apply` — webhook handler stub for .");
    expect(lines).toContain("//   // to this endpoint can forge a  webhook.");

    // `${capitalize(provider)}` site: the `s === ""` early return keeps
    // `codePointAt(0)`'s undefined out of `String.fromCodePoint`, which
    // would throw a RangeError on NaN — the handler name is just "handle".
    expect(lines).toContain(
      "// export async function handleWebhook(req: Request): Promise<Response> {",
    );

    // `${webhookSecretKeyFor(provider)}` sites: `"".toUpperCase()` is "" —
    // the default switch case emitted the bare `_WEBHOOK_SECRET` suffix at
    // both reveal lines, each otherwise byte-exact.
    expect(lines).toContain("//   phantom reveal _WEBHOOK_SECRET");
    expect(lines).toContain("//   // (`phantom reveal _WEBHOOK_SECRET`) and compare in");
    expect(count(stub, "phantom reveal _WEBHOOK_SECRET")).toBe(2);

    // Single pass, every slot resolved: no `${...}` residue anywhere.
    expect(stub).not.toContain("${");

    // The sibling slots took their generic defaults in the same pass — the
    // empty name reaches none of the known-provider switch cases.
    expect(lines).toContain('//   const signature = req.headers.get("x-webhook-signature");');
    expect(lines).toContain("//   // Verify per the provider's documented signature scheme.");
    expect(verificationHintFor("")).toBe(verificationHintFor("zzq"));
  });

  it("reports the empty name in skipped byte-for-byte beside a wired known provider", async () => {
    // Through `wirePhantomForRecipe` the empty name matches no catalog
    // provider: `skipped` holds the empty string itself — pushed, not
    // dropped — while the known provider listed beside it wires normally,
    // unaffected by the empty neighbour.
    const stubPath = join(dir, ".stack", "webhooks", "github.ts");
    const result = await wirePhantomForRecipe(recipe("", "github"), { cwd: dir });

    expect(result).toEqual({
      present: [],
      missing: ["github:GITHUB_TOKEN"],
      webhooks: [stubPath],
      skipped: [""],
    });
    expect(result.skipped).toHaveLength(1);
    expect(result.skipped[0]).toBe("");

    // Only github's documented stub lands — nothing for the empty name, and
    // the stub on disk is the same render `webhookStubFor` returns.
    expect(readdirSync(join(dir, ".stack", "webhooks"))).toEqual(["github.ts"]);
    expect(readFileSync(stubPath, "utf-8")).toBe(webhookStubFor("github"));
    expect(existsSync(join(dir, ".stack", "webhooks", ".ts"))).toBe(false);

    // The whole call log is reads (`--version`, `list`); the vault file
    // still parses to an empty object — an empty name provokes no write.
    expect(harness.calls().every((c) => c.cmd === "--version" || c.cmd === "list")).toBe(true);
    expect(harness.callsTo("add")).toEqual([]);
    expect(JSON.parse(readFileSync(harness.vaultPath, "utf-8"))).toEqual({});
  });
});
