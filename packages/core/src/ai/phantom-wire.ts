/**
 * Recipe → Phantom vault check + webhook stub materializer.
 *
 * For each provider in a Recipe:
 *   1. Report which declared secrets are already in the Phantom vault and
 *      which are missing. `stack add` stores the real values; this step never
 *      writes to the vault. Phantom Secrets refuses secret values in argv and
 *      denies overwriting existing names, so placeholder entries would either
 *      fail or block the real value from landing later.
 *   2. For webhook-capable providers (Stripe, Clerk, Supabase, GitHub),
 *      scaffold a commented-out handler stub in `.stack/webhooks/<provider>.ts`
 *      as an example only. It does not verify signatures; the user must
 *      implement provider-specific verification before deploying a handler.
 *
 * An opt-out (`--no-wire`) skips both steps.
 *
 * Recipe manifests are unsigned: signature verification is not implemented.
 * Checking provider names against the catalog does not authenticate a recipe's
 * origin or integrity; callers must use recipes from a trusted source.
 */

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { findProviderRef } from "../catalog.ts";
import { PhantomNotInstalledError } from "../errors.ts";
import { assertPhantomInstalled, listSecrets } from "../phantom.ts";
import type { Recipe } from "./recipe.ts";

export interface WireResult {
  /** `PROVIDER:SECRET_NAME` entries already stored in the Phantom vault. */
  present: string[];
  /** `PROVIDER:SECRET_NAME` entries the recipe declares but the vault lacks. */
  missing: string[];
  /** Absolute paths of webhook stub files created. */
  webhooks: string[];
  /** Names of providers skipped (phantom missing, vault unreadable, unknown provider). */
  skipped: string[];
}

/**
 * Providers with webhooks worth pre-wiring. Keep this list tight and update
 * the provider-specific secret and signature header mappings for each entry.
 */
const WEBHOOK_PROVIDERS = new Set(["stripe", "clerk", "supabase", "github"]);

export async function wirePhantomForRecipe(
  recipe: Recipe,
  opts: { cwd?: string; noWire?: boolean } = {},
): Promise<WireResult> {
  const result: WireResult = { present: [], missing: [], webhooks: [], skipped: [] };
  if (opts.noWire) return result;

  const cwd = opts.cwd ?? process.cwd();

  try {
    await assertPhantomInstalled();
  } catch (err) {
    if (err instanceof PhantomNotInstalledError) {
      // Phantom missing → skip the vault check but still drop webhook stubs
      // (they're just files). Surface the provider names so the CLI can tell
      // the user why nothing landed in the vault.
      for (const p of recipe.providers) result.skipped.push(p.name);
      for (const p of recipe.providers) {
        if (WEBHOOK_PROVIDERS.has(p.name)) {
          const path = await writeWebhookStub(cwd, p.name);
          result.webhooks.push(path);
        }
      }
      return result;
    }
    throw err;
  }

  const stored = await listVaultNames(cwd);

  for (const { name } of recipe.providers) {
    const ref = findProviderRef(name);
    if (!ref || !stored) {
      result.skipped.push(name);
    } else {
      for (const secret of ref.secrets) {
        (stored.has(secret) ? result.present : result.missing).push(`${name}:${secret}`);
      }
    }

    if (WEBHOOK_PROVIDERS.has(name)) {
      const path = await writeWebhookStub(cwd, name);
      result.webhooks.push(path);
    }
  }

  return result;
}

/**
 * Secret names in the project's Phantom vault, via `phantom list --json`
 * (names and metadata only, never values). Returns undefined when the vault
 * can't be read (not initialized, older Phantom without `--json`, etc).
 */
async function listVaultNames(cwd: string): Promise<Set<string> | undefined> {
  try {
    return new Set(await listSecrets(cwd));
  } catch {
    return undefined;
  }
}

async function writeWebhookStub(cwd: string, provider: string): Promise<string> {
  const path = resolve(cwd, ".stack", "webhooks", `${provider}.ts`);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, webhookStubFor(provider), "utf-8");
  return path;
}

function webhookStubFor(provider: string): string {
  const base = `// Auto-generated by \`stack apply\` — webhook handler stub for ${provider}.
// Fill in the secret retrieval + signature verification before deploying.
// This entire example is commented out and does not verify signatures.
// If uncommented as-is, it accepts any non-empty signature header and returns
// 200 without authenticating the request. Implement verification first.
//
// The secret lives in Phantom; read it at call time with:
//   phantom reveal ${webhookSecretKeyFor(provider)}
//
// export async function handle${capitalize(provider)}Webhook(req: Request): Promise<Response> {
//   const signature = req.headers.get("${signatureHeaderFor(provider)}");
//   if (!signature) return new Response("Missing signature", { status: 400 });
//   const body = await req.text();
//   // TODO: verify this webhook request body using the provider's signature scheme.
//   // Verification inputs include the body, signature, webhook secret, and any
//   // additional inputs required by the provider's scheme.
//   // The body is unverified; a present signature header does not authenticate it.
//   // Verify the unmodified body before parsing, trusting, or acting on its contents.
//   // Reject requests whose signatures are missing or invalid; only process the
//   // body after successful provider-specific verification.
//   return new Response("ok", { status: 200 });
// }
`;
  return base;
}

function webhookSecretKeyFor(provider: string): string {
  switch (provider) {
    case "stripe":
      return "STRIPE_WEBHOOK_SECRET";
    case "clerk":
      return "CLERK_WEBHOOK_SECRET";
    case "supabase":
      return "SUPABASE_WEBHOOK_SECRET";
    case "github":
      return "GITHUB_WEBHOOK_SECRET";
    default:
      return `${provider.toUpperCase()}_WEBHOOK_SECRET`;
  }
}

function signatureHeaderFor(provider: string): string {
  switch (provider) {
    case "stripe":
      return "stripe-signature";
    case "clerk":
      return "svix-signature";
    case "supabase":
      return "x-supabase-signature";
    case "github":
      return "x-hub-signature-256";
    default:
      return "x-webhook-signature";
  }
}

function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}
