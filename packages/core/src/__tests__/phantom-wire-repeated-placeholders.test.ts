import { expect, it } from "bun:test";
import { webhookStubFor } from "../ai/phantom-wire.ts";

it.each([
  ["stripe", "STRIPE_WEBHOOK_SECRET"],
  ["clerk", "CLERK_WEBHOOK_SECRET"],
  ["supabase", "SUPABASE_WEBHOOK_SECRET"],
  ["github", "GITHUB_WEBHOOK_SECRET"],
])("fills every repeated placeholder for %s", (provider, secret) => {
  const stub = webhookStubFor(provider);
  const lines = stub.split("\n");

  expect(lines.filter((line) => line.includes("webhook handler stub for"))).toEqual([
    `// Auto-generated by \`stack apply\` — webhook handler stub for ${provider}.`,
  ]);
  expect(lines.filter((line) => line.includes("webhook."))).toEqual([
    `//   // to this endpoint can forge a ${provider} webhook.`,
  ]);
  expect(lines.filter((line) => line.includes("phantom reveal"))).toEqual([
    `//   phantom reveal ${secret}`,
    `//   // (\`phantom reveal ${secret}\`) and compare in`,
  ]);
  expect(stub).not.toContain("${");
});

it("preserves a single quote after a dollar sign in replacement text", () => {
  const stub = webhookStubFor("pay$'co");
  const lines = stub.split("\n");

  expect(lines).toContain("// Auto-generated by `stack apply` — webhook handler stub for pay$'co.");
  expect(lines).toContain("//   // to this endpoint can forge a pay$'co webhook.");
  expect(lines).toContain(
    "// export async function handlePay$'coWebhook(req: Request): Promise<Response> {",
  );
  expect(lines.filter((line) => line.includes("phantom reveal"))).toEqual([
    "//   phantom reveal PAY$'CO_WEBHOOK_SECRET",
    "//   // (`phantom reveal PAY$'CO_WEBHOOK_SECRET`) and compare in",
  ]);
});

it.each([
  ["payco", "PAYCO_WEBHOOK_SECRET"],
  ["pay$'co", "PAY$'CO_WEBHOOK_SECRET"],
])("expands the leading provider slot and preserves its suffix for %s", (provider, expected) => {
  // The fallback secret-name template starts with the provider interpolation,
  // followed immediately by the literal _WEBHOOK_SECRET suffix.
  const revealLines = webhookStubFor(provider)
    .split("\n")
    .filter((line) => line.startsWith("//   phantom reveal "));

  expect(revealLines).toEqual([`//   phantom reveal ${expected}`]);
});
