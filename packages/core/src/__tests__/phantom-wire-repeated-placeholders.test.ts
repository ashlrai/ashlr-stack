import { expect, it } from "bun:test";
import { webhookStubFor } from "../ai/phantom-wire.ts";

it.each([
  ["stripe", "STRIPE_WEBHOOK_SECRET"],
  ["clerk", "CLERK_WEBHOOK_SECRET"],
  ["supabase", "SUPABASE_WEBHOOK_SECRET"],
  ["github", "GITHUB_WEBHOOK_SECRET"],
])("fills every repeated placeholder for %s", (provider, secret) => {
  const stub = webhookStubFor(provider);
  const lines = stub.split("\n");

  expect(lines.filter((line) => line.includes("webhook handler stub for"))).toEqual([
    `// Auto-generated by \`stack apply\` — webhook handler stub for ${provider}.`,
  ]);
  expect(lines.filter((line) => line.includes("webhook."))).toEqual([
    `//   // to this endpoint can forge a ${provider} webhook.`,
  ]);
  expect(lines.filter((line) => line.includes("phantom reveal"))).toEqual([
    `//   phantom reveal ${secret}`,
    `//   // (\`phantom reveal ${secret}\`) and compare in`,
  ]);
  expect(stub).not.toContain("${");
});
