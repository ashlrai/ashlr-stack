import { describe, expect, it, setDefaultTimeout } from "bun:test";
import { existsSync, readFileSync } from "node:fs";
import { setupFakePhantom } from "../packages/core/src/__tests__/_harness.ts";
import { wirePhantomForRecipe } from "../packages/core/src/ai/phantom-wire.ts";

setDefaultTimeout(30_000);

const docUrl = new URL("../docs/phantom-wire-example-reading-guide.md", import.meta.url);
const doc = readFileSync(docUrl, "utf8");

describe("Phantom wire example reading guide", () => {
  it("follows generated examples in order and identifies their trust boundary", async () => {
    const providers = ["stripe", "clerk", "supabase", "github"];
    const harness = setupFakePhantom();
    try {
      const result = await wirePhantomForRecipe(
        { id: "guide", query: "", createdAt: "", providers: providers.map((name) => ({ name })) },
        { cwd: harness.dir },
      );
      expect(result.webhooks).toHaveLength(providers.length);
      const guideSteps = [
        "**Preamble.**",
        "**Secret guidance.**",
        "**Handler and header.**",
        "**Body.**",
        "**Security TODO.**",
        "**Success response.**",
      ];
      expect(guideSteps.map((step) => doc.indexOf(step))).toEqual(
        guideSteps.map((step) => doc.indexOf(step)).sort((a, b) => a - b),
      );
      for (const step of guideSteps) expect(doc).toContain(step);
      expect(doc).toContain("signature verification is NOT\n   implemented here.");
      expect(doc).toContain("any non-empty\n   value");
      expect(doc).toContain("attacker-controlled input");
      expect(doc).toContain("not an active handler or a verified request");

      const excerpt = doc.match(/```ts\n([\s\S]*?)\n```/)?.[1];
      expect(excerpt).toBeDefined();
      if (!excerpt) throw new Error("Missing commented Stripe excerpt");
      expect(excerpt.split("\n").every((line) => line.startsWith("//"))).toBe(true);
      expect(excerpt).toContain("TODO(security): signature verification is NOT implemented here.");

      for (const [index, provider] of providers.entries()) {
        const stub = readFileSync(result.webhooks[index], "utf8");
        expect(stub.split("\n").every((line) => !line || line.startsWith("//"))).toBe(true);
        if (provider === "stripe") expect(stub).toContain(excerpt);
        const steps = [
          "Auto-generated by",
          "phantom reveal ",
          "export async function handle",
          "req.headers.get(",
          "await req.text()",
          "TODO(security): signature verification is NOT implemented here.",
          'return new Response("ok", { status: 200 })',
        ];
        const offsets = steps.map((step) => stub.indexOf(step));
        expect(offsets.every((offset) => offset >= 0)).toBe(true);
        expect(offsets).toEqual([...offsets].sort((a, b) => a - b));
        const header = stub.match(/req\.headers\.get\("([^"]+)"\)/)?.[1];
        const secret = stub.match(/phantom reveal ([A-Z_]+)/)?.[1];
        expect(header).toBeDefined();
        expect(secret).toBeDefined();
        const row = doc.split("\n").find((line) => line.toLowerCase().startsWith(`| ${provider} |`));
        expect(row).toContain(`\`${header}\` | \`${secret}\``);
      }
      expect(harness.callsTo("reveal")).toEqual([]);
      for (const [, link] of doc.matchAll(/\]\(([^)#]+)(?:#[^)]+)?\)/g)) {
        expect(existsSync(new URL(link, docUrl))).toBe(true);
      }
    } finally {
      harness.cleanup();
    }
  });
});
